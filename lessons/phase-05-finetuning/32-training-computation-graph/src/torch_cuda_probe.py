#!/usr/bin/env python3
"""Optional CUDA measurement of a real PyTorch training step.

Install PyTorch using the command generated by the official PyTorch selector
for the learner's CUDA/driver combination. This file does not choose a wheel
index on the learner's behalf.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch
from torch import nn
from torch.utils.checkpoint import checkpoint


class TinyStack(nn.Module):
    def __init__(self, hidden_size: int, layers: int) -> None:
        super().__init__()
        self.layers = nn.ModuleList(
            nn.Sequential(
                nn.Linear(hidden_size, hidden_size * 4, bias=False),
                nn.GELU(),
                nn.Linear(hidden_size * 4, hidden_size, bias=False),
            )
            for _ in range(layers)
        )
        self.output = nn.Linear(hidden_size, hidden_size, bias=False)

    def forward(self, tensor: torch.Tensor, use_checkpoint: bool) -> torch.Tensor:
        for layer in self.layers:
            if use_checkpoint:
                tensor = checkpoint(layer, tensor, use_reentrant=False)
            else:
                tensor = layer(tensor)
        return self.output(tensor)


def allocated() -> int:
    return int(torch.cuda.memory_allocated())


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--hidden-size", type=int, default=1024)
    parser.add_argument("--layers", type=int, default=8)
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--sequence-length", type=int, default=512)
    parser.add_argument("--checkpoint", action="store_true")
    args = parser.parse_args()

    if not torch.cuda.is_available():
        raise SystemExit("CUDA is not available; run the CPU lab instead")
    if not torch.cuda.is_bf16_supported():
        raise SystemExit("This bounded probe expects a BF16-capable GPU")

    torch.manual_seed(3201)
    torch.cuda.manual_seed_all(3201)
    device = torch.device("cuda")
    torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()

    model = TinyStack(args.hidden_size, args.layers).to(
        device=device,
        dtype=torch.bfloat16,
    )
    optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4)
    after_model = allocated()

    inputs = torch.randn(
        args.batch_size,
        args.sequence_length,
        args.hidden_size,
        device=device,
        dtype=torch.bfloat16,
        requires_grad=True,
    )
    targets = torch.zeros_like(inputs)
    optimizer.zero_grad(set_to_none=True)
    outputs = model(inputs, args.checkpoint)
    loss = torch.nn.functional.mse_loss(outputs.float(), targets.float())
    after_forward = allocated()
    loss.backward()
    after_backward = allocated()
    optimizer.step()
    torch.cuda.synchronize()

    payload = {
        "schema_version": 1,
        "experiment": "torch-cuda-training-step",
        "torch_version": torch.__version__,
        "device_name": torch.cuda.get_device_name(),
        "checkpoint": args.checkpoint,
        "shape": {
            "batch_size": args.batch_size,
            "sequence_length": args.sequence_length,
            "hidden_size": args.hidden_size,
            "layers": args.layers,
        },
        "loss": float(loss.detach().cpu()),
        "bytes": {
            "after_model": after_model,
            "after_forward": after_forward,
            "after_backward": after_backward,
            "peak_allocated": int(torch.cuda.max_memory_allocated()),
            "peak_reserved": int(torch.cuda.max_memory_reserved()),
        },
        "notes": [
            "allocated excludes memory held outside the PyTorch allocator",
            "reserved includes allocator cache but not every driver allocation",
            "compare checkpoint on/off in fresh processes",
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(payload["bytes"], sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
